_AND_AA_TABLE = bytes(b & 0xAA for b in range(256))


def checksum(data: bytes) -> int:
    
    return sum(data.translate(_AND_AA_TABLE)) & 0xFF


_ENC_TABLE_EVEN = bytes(ENC_TABLE[b] ^ DEFAULT_KEY_A for b in range(256))
_ENC_TABLE_ODD = bytes(ENC_TABLE[b] ^ DEFAULT_KEY_B for b in range(256))

_DEC_TABLE_EVEN = bytes(DEC_TABLE[b ^ DEFAULT_KEY_A] for b in range(256))
_DEC_TABLE_ODD = bytes(DEC_TABLE[b ^ DEFAULT_KEY_B] for b in range(256))


def _translate_alternating(data: bytes, even_table: bytes, odd_table: bytes) -> bytes:
    
    even = data[0::2].translate(even_table)
    odd = data[1::2].translate(odd_table)

    out = bytearray(len(data))
    out[0::2] = even
    out[1::2] = odd
    return bytes(out)


def encode_payload(
    plain_payload: bytes,
    key_a: int = DEFAULT_KEY_A,
    key_b: int = DEFAULT_KEY_B,
) -> bytes:
    if key_a == DEFAULT_KEY_A and key_b == DEFAULT_KEY_B:
        return _translate_alternating(plain_payload, _ENC_TABLE_EVEN, _ENC_TABLE_ODD)

    return bytes(
        ENC_TABLE[b] ^ (key_a if (i % 2 == 0) else key_b)
        for i, b in enumerate(plain_payload)
    )


def decode_payload(
    encrypted_payload: bytes,
    key_a: int = DEFAULT_KEY_A,
    key_b: int = DEFAULT_KEY_B,
) -> bytes:
    if key_a == DEFAULT_KEY_A and key_b == DEFAULT_KEY_B:
        return _translate_alternating(encrypted_payload, _DEC_TABLE_EVEN, _DEC_TABLE_ODD)

    return bytes(
        DEC_TABLE[b ^ (key_a if (i % 2 == 0) else key_b)]
        for i, b in enumerate(encrypted_payload)
    )


def encode_with_checksum(
    plain_payload: bytes,
    key_a: int = DEFAULT_KEY_A,
    key_b: int = DEFAULT_KEY_B,
) -> tuple[bytes, int]:
    
    return encode_payload(plain_payload, key_a, key_b), checksum(plain_payload)


def decode_with_checksum(
    encrypted_payload: bytes,
    checksum_byte: int | None = None,
    key_a: int = DEFAULT_KEY_A,
    key_b: int = DEFAULT_KEY_B,
) -> tuple[bytes, bool | None, int]:
    
    decoded = decode_payload(encrypted_payload, key_a, key_b)
    calculated = checksum(decoded)
    ok = None if checksum_byte is None else (calculated == checksum_byte)
    return decoded, ok, calculated




def enc(pt: bytes, port: int = 5125) -> bytes:
    return pt


def dec(raw: bytes, port: int = 5125) -> bytes:
    return raw
